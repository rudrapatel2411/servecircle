const langs = ['en', 'hi', 'gu'];

for (const lang of langs) {
  const filePath = path.join(__dirname, `${lang}.js`);
  let content = fs.readFileSync(filePath, 'utf8');
  
  if (content.includes('petFlow: {')) {
    console.log(`petFlow already exists in ${lang}.js`);
    continue;
  }

  const flowString = `,\n  petFlow: ${JSON.stringify(petFlowTranslations[lang], null, 4)}`;
  
  const lastBraceIndex = content.lastIndexOf('};');
  if (lastBraceIndex !== -1) {
    content = content.substring(0, lastBraceIndex) + flowString + '\n' + content.substring(lastBraceIndex);
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Added petFlow to ${lang}.js`);
  }
}
